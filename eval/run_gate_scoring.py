"""CLI: run every validate gate against the mutant corpus and write the table.

    python -m eval.run_gate_scoring [--issue 990157]

Really runs the gates as subprocesses — nine arms times 29 gates — so it takes a
couple of minutes and is deliberately not wired into pytest's 30s budget. The
table it writes is committed; `tests/unit/test_mutants.py` reads it and re-runs
the artifact-sensitive subset live to check the file still tells the truth.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from eval.artifact_mutants import OPERATORS  # noqa: E402
from eval.gate_scoring import (  # noqa: E402
    ARMS,
    CLEAN_ARM,
    NO_ARTIFACT_ARM,
    RESULTS_JSON,
    RESULTS_MD,
    build_table,
    discover_gates,
    run_arms,
)

DEFAULT_SYNTHETIC_ISSUE = 990157


def _cell(row: dict, operator: str) -> str:
    return "caught" if row["caught"][operator] else "—"


def render_markdown(table: dict) -> str:
    ops = table["operators"]
    short = {op: op.replace("_", " ") for op in ops}

    lines: list[str] = []
    lines.append("# Gate x operator sensitivity — issue #1457 (HE-C/P-EVAL-15)")
    lines.append("")
    lines.append(
        "Generated by `python -m eval.run_gate_scoring`. Do not hand-edit: "
        "`tests/unit/test_mutants.py::test_score_table_covers_all_29_gates` reads "
        "the JSON beside this file."
    )
    lines.append("")
    lines.append("## Read this before reading the numbers")
    lines.append("")
    lines.append(table["honestyNote"])
    lines.append("")
    lines.append("## Method")
    lines.append("")
    lines.append(
        f"- **{table['gateCount']} gates**, every `*.py` in "
        "`agent-runtime/scripts/validate/`, including the ones that turn out to "
        "catch nothing."
    )
    lines.append(
        f"- **{len(ARMS)} arms**: `{NO_ARTIFACT_ARM}` (no bodies, no workflow "
        f"cache), `{CLEAN_ARM}` (unmutated fixture), and one per operator."
    )
    lines.append(
        "- Mutants are generated from the three artifact **schemas**, not from "
        "the surviving corpus: only ~15 bodies exist on disk, so a corpus-driven "
        "population would run at N is about 15 and would block on HE-B."
    )
    lines.append(
        "- Each mutant is schema-valid and carries **exactly one** planted "
        "defect, asserted by diffing it against its clean baseline."
    )
    lines.append(
        "- A gate **catches** an operator iff it PASSes on `clean` and FAILs on "
        "that operator's arm. The clean precondition matters: without it a gate "
        "that fails on everything would score a perfect seven."
    )
    lines.append(
        "- Exit code 0 is PASS, 1 is FAIL; anything else, a crash, or a timeout "
        "is `ERROR` and is never folded into PASS."
    )
    lines.append("")
    lines.append("## Three outcomes, never collapsed")
    lines.append("")
    lines.append(
        "Every gate lands in exactly one of these. The middle one is the reason "
        "the table is worth having: fold it into the first and the sensitivity "
        "number inflates; fold it into the last and gates get condemned that this "
        "population never actually tested."
    )
    lines.append("")
    lines.append("| outcome | count | meaning |")
    lines.append("|---|---|---|")
    lines.append(
        f"| **caught** | {table['caughtCount']} | PASSed the clean record, FAILed "
        "at least one planted defect. Real, measured sensitivity. |"
    )
    lines.append(
        f"| **silent** | {table['silentCount']} | PASSed the clean record *and* "
        "PASSed every planted defect. It judged a record it was built to judge "
        "and said nothing. **Deletion candidates.** |"
    )
    lines.append(
        f"| **fail-closed on a synthetic precondition** | {table['failClosedCount']} "
        "| Never reached PASS on the clean arm: the synthetic issue number "
        "resolves to no GitHub issue, or the working tree has real stale "
        "branches. **Correct behaviour.** Not sensitivity, not a false positive, "
        "not a deletion candidate - simply unscored by this population. |"
    )
    lines.append("")
    lines.append("## Headline")
    lines.append("")
    lines.append(f"- Gates scored: **{table['gateCount']}**")
    lines.append(
        f"- Gates catching **zero** operators: **{table['zeroCatchCount']}** "
        f"of {table['gateCount']}."
    )
    lines.append(
        f"  - of which **{table['silentCount']}** are **silent**: they PASSed the "
        "clean arm and still caught nothing — deletion candidates, not tuning "
        "candidates."
    )
    lines.append(
        f"  - and **{table['failClosedCount']}** **failed closed on a synthetic "
        "precondition**, so this population never scored them. Explicitly *not* "
        "deletion candidates: calling them deleteable would be the same vacuous "
        "inference this slice exists to end."
    )
    lines.append(
        f"- Operators caught by **no** gate: **{len(table['uncaughtOperators'])}** "
        f"of {len(ops)}"
        + (
            f" — {', '.join('`' + o + '`' for o in table['uncaughtOperators'])}"
            if table["uncaughtOperators"]
            else ""
        )
    )
    lines.append(
        f"- Gates that could not reach a verdict in some arm (`ERROR`): "
        f"**{len(table['erroredGates'])}**"
        + (
            f" — {', '.join('`' + g + '`' for g in table['erroredGates'])}"
            if table["erroredGates"]
            else ""
        )
    )
    lines.append(
        f"- False positives on the clean record (PASS with no artifacts -> FAIL "
        f"with a clean one): **{len(table['falsePositivesOnClean'])}**"
        + (
            f" — {', '.join('`' + g + '`' for g in table['falsePositivesOnClean'])}"
            if table["falsePositivesOnClean"]
            else ". This is the false-positive floor."
        )
    )
    lines.append(
        f"- Gates not PASSing on the clean arm at all: "
        f"**{len(table['cleanArmFailures'])}** — the fail-closed set above. They "
        "refused a verdict because a precondition the fixture cannot synthesise "
        "is missing, not because they detected anything; they are structurally "
        "unable to catch anything here and are reported rather than laundered "
        "into the sensitivity number."
    )
    lines.append("")
    lines.append("## gate x operator")
    lines.append("")
    header = ["gate", f"`{CLEAN_ARM}`", *[short[o] for o in ops], "catches"]
    lines.append("| " + " | ".join(header) + " |")
    lines.append("|" + "|".join(["---"] * len(header)) + "|")
    for row in table["rows"]:
        cells = [
            f"`{row['gate']}`",
            row["arms"][CLEAN_ARM]["verdict"],
            *[_cell(row, o) for o in ops],
            str(row["catchCount"]),
        ]
        lines.append("| " + " | ".join(cells) + " |")
    lines.append("")
    lines.append("## Failure class behind each operator")
    lines.append("")
    for op in ops:
        lines.append(f"- **`{op}`** — {table['failureClasses'][op]}")
    lines.append("")
    lines.append("## Silent gates — deletion candidates")
    lines.append("")
    lines.append(
        "These reached PASS on the clean record, so they were genuinely scored, "
        "and then passed every planted defect. That is evidence of insensitivity "
        "to our *own named* failure classes, which is the strongest negative "
        "signal available today — but see the honesty note: a gate may still "
        "catch something we have not thought to mutate."
    )
    lines.append("")
    for gate in table["silentGates"]:
        row = next(r for r in table["rows"] if r["gate"] == gate)
        sensitive = (
            "read the record but its verdict never moved"
            if row["artifactSensitive"]
            else "never read the record at all"
        )
        lines.append(f"- `{gate}` — PASSed all nine arms; {sensitive}.")
    lines.append("")
    lines.append("## Fail-closed on a synthetic precondition — NOT deletion candidates")
    lines.append("")
    lines.append(
        "These never reached PASS on the clean arm, so no catch was possible and "
        "no conclusion about their sensitivity is available from this run. They "
        "are coupled to a live GitHub issue (the synthetic issue number resolves "
        "to nothing, and they correctly refuse to guess) or to real working-tree "
        "state. **Their failures must never be counted as catches** — that is the "
        "one substitution that would make the whole table read better than the "
        "truth. Scoring them needs a corpus-derived population on a real issue: a "
        "second population, out of scope here."
    )
    lines.append("")
    for gate in table["failClosedGates"]:
        row = next(r for r in table["rows"] if r["gate"] == gate)
        detail = row["arms"][CLEAN_ARM]["detail"] or row["arms"][CLEAN_ARM]["verdict"]
        lines.append(f"- `{gate}` — {row['arms'][CLEAN_ARM]['verdict']}: {detail}")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--issue", type=int, default=DEFAULT_SYNTHETIC_ISSUE)
    args = parser.parse_args(argv)

    gates = discover_gates()
    print(f"scoring {len(gates)} gates x {len(ARMS)} arms ({len(OPERATORS)} operators)")

    arms = run_arms(args.issue, gates)
    table = build_table(args.issue, arms)

    RESULTS_JSON.parent.mkdir(parents=True, exist_ok=True)
    RESULTS_JSON.write_text(json.dumps(table, indent=2) + "\n")
    RESULTS_MD.write_text(render_markdown(table))

    print(f"zero-catch gates: {table['zeroCatchCount']}/{table['gateCount']}")
    print(f"uncaught operators: {table['uncaughtOperators']}")
    print(f"errored gates: {table['erroredGates']}")
    print(f"false positives on clean: {table['falsePositivesOnClean']}")
    print(f"wrote {RESULTS_JSON} and {RESULTS_MD}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
