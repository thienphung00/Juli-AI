_BY_KEY: dict[tuple[str, str], Expectation] = {e.key: e for e in EXPECTATIONS}


def expectation_for(method: str, path: str) -> Expectation | None:
    """The expectation for a concrete request path (numeric id segments -> ``{}``)."""
    template = _ID_SEGMENT.sub("/{}", path.split("?", 1)[0].rstrip("/"))
    return _BY_KEY.get((method.upper(), template))


def check_response_drift(method: str, path: str, data: Any) -> None:
    """Report drift for a successful response of a watched endpoint. Never raises."""
    try:
        expectation = expectation_for(method, path)
        if expectation is None or not isinstance(data, dict):
            return
        report_schema_drift(
            PLATFORM,
            expectation.endpoint,
            data,
            expectation.expected,
            documented=expectation.documented,
        )
    except Exception:  # a drift check must never break the call it watches
        return
