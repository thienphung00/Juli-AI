PLATFORM = "tiktok"
_PLACEHOLDER = re.compile(r"\{[^}]*\}")
# TikTok ids are 15-20 digits; the six-digit version segment must stay as is.
_ID_SEGMENT = re.compile(r"/\d{7,}(?=/|$)")


@dataclass(frozen=True, slots=True)
class Expectation:
    endpoint: str  # "METHOD /path/{placeholder}" as in the docs
    label: str
    expected: frozenset[str]
    documented: frozenset[str] = frozenset()

    @property
    def key(self) -> tuple[str, str]:
        method, _, path = self.endpoint.partition(" ")
        return method, _PLACEHOLDER.sub("{}", path)


