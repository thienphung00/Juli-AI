"""Fields Juli's TikTok client relies on, per endpoint, for runtime drift reports (D31.10).

``expected`` — response fields (relative to the ``data`` envelope) that current code
reads: ``schemas.py`` models, ``mapping.py`` normalizers/expanders, and the
shop-diagnosis / promotion readers. Only fields TikTok returns on every row are
listed; optional ones (``audit``, ``cancel_reason``, a root list that is omitted on
an empty page...) would read as "missing" on healthy responses.

``documented`` — the other fields the Partner Center docs list under the same
parent objects, from ``infra/apiwatch/snapshots/tiktok.json`` (2026-10-12). A field
outside both sets is reported as ``unexpected`` (TikTok added it).

When the code starts reading a new field or a version pin moves, update the entry;
``tests/unit/test_tiktok_schema_expectations.py`` checks every expected field is
documented in the apiwatch snapshot. Runbook: docs/runbooks/apiwatch.md.
"""

