#!/usr/bin/env python3
"""Write ``apps/demo/src/lib/metrics/registry.generated.ts`` from the Python metric registry.

The TS file is the frontend's copy of the registry's ids, labels, units, rounding and
``summable`` (doc ``docs/architecture/metric-registry.md`` §3, §10). Never edit it by hand:
change ``backend/src/juli_backend/services/metrics/registry.py`` and run this script.
``tests/unit/test_metric_contract.py`` fails when the committed file is stale.

Usage: ``python scripts/gen_metric_contract.py [--check]``
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "apps/demo/src/lib/metrics/registry.generated.ts"

HEADER = (
    "// Generated by scripts/gen_metric_contract.py from services/metrics/registry.py"
    " -- do not edit.\n"
    "// Regenerate: python scripts/gen_metric_contract.py\n"
)


def _q(text: str) -> str:
    return json.dumps(text, ensure_ascii=False)


def _union(name: str, values: list[str]) -> list[str]:
    return [
        f"export type {name} =",
        *(f"  | {_q(v)}" for v in values[:-1]),
        f"  | {_q(values[-1])};",
    ]


def render() -> str:
    if str(ROOT / "backend/src") not in sys.path:
        sys.path.insert(0, str(ROOT / "backend/src"))
    from juli_backend.services.capabilities.registry import CAPABILITIES
    from juli_backend.services.metrics.registry import (
        DERIVATION_VERSION,
        METRICS,
        Comparison,
        Rounding,
        Unit,
    )

    lines = [
        HEADER.rstrip("\n"),
        "",
        f"export const DERIVATION_VERSION = {_q(DERIVATION_VERSION)};",
        "",
    ]
    lines += _union("MetricUnit", [u.value for u in Unit]) + [""]
    lines += _union("MetricRounding", [r.value for r in Rounding]) + [""]
    lines += _union("MetricId", list(METRICS)) + [""]
    lines += [
        "export interface MetricDefinition {",
        "  readonly id: MetricId;",
        "  readonly label_vi: string;",
        "  readonly unit: MetricUnit;",
        "  readonly rounding: MetricRounding;",
        "  readonly summable: boolean;",
        "  readonly perDayAllowed: boolean;",
        "}",
        "",
        "export const METRIC_DEFS: Readonly<Record<MetricId, MetricDefinition>> = {",
    ]
    for m in METRICS.values():
        lines.append(
            f"  {m.id}: {{ id: {_q(m.id)}, label_vi: {_q(m.label_vi)}, unit: {_q(m.unit.value)}, "
            f"rounding: {_q(m.rounding.value)}, summable: {str(m.summable).lower()}, "
            f"perDayAllowed: {str(m.summable).lower()} }},"
        )
    lines += ["};", ""]
    caps = ", ".join(_q(c) for c in CAPABILITIES)
    lines += [f"export const CAPABILITY_IDS = [{caps}] as const;", ""]
    lines += ["export type CapabilityId = (typeof CAPABILITY_IDS)[number];", ""]
    comps = ", ".join(_q(c.value) for c in Comparison)
    lines += [f"export const COMPARISON_KINDS = [{comps}] as const;", ""]
    lines += ["export type ComparisonKind = (typeof COMPARISON_KINDS)[number];", ""]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"stale: {OUT.relative_to(ROOT)} -- run scripts/gen_metric_contract.py")
            return 1
        return 0
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
