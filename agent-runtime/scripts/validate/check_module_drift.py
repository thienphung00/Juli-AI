def module_symbols(module_path: str) -> tuple[set[str], set[str]]:
    """(documented, actual) public symbols for a module path from the map."""
    module_md = backend_module_root(module_path) / "MODULE.md"
    return parse_module_md_public_symbols(module_md), module_public_symbols_from_code(module_path)


def _allowed(module_path: str, kind: str) -> set[str]:
    entry = KNOWN_DRIFT_ALLOWLIST.get(module_path, {}).get(kind)
    return set(entry.symbols) if entry else set()


def run_check(issue: int) -> tuple[bool, str, dict[str, Any]]:  # noqa: ARG001
    modules = parse_architecture_map()
    try:
        changed = git_changed_files()
    except ChangedFilesUnresolved as exc:
        # Never a silent pass: an unresolvable diff is reported with its cause,
        # the same way harness_bootstrap_pin.py degrades (#1540, #1571).
        return (
            False,
            f"Changed-file set unresolved: {exc.reason}",
            {
                "drift": [],
                "missingInterfaces": [],
                "touchedModules": [],
                "allowlisted": [],
                "changedFilesUnresolved": exc.reason,
            },
        )
    touched: set[str] = set()
    for path in changed:
        mod = module_for_file(path, modules)
        if mod:
            touched.add(mod)
    drift: list[dict] = []
    allowlisted: list[str] = []
    for module_path in sorted(touched):
        info = modules.get(module_path)
        if not info or info.tier >= 3:
            continue
        module_md = backend_module_root(module_path) / "MODULE.md"
        if not module_md.exists():
            drift.append({"module": module_path, "error": "MODULE.md missing"})
            continue
        documented, actual = module_symbols(module_path)
        excused_missing = _allowed(module_path, "undocumented")
        excused_orphan = _allowed(module_path, "orphan")
        missing = sorted((actual - documented) - excused_missing)
        orphans = sorted((documented - actual) - excused_orphan)
        allowlisted.extend(
            f"{module_path}:undocumented:{s}"
            for s in sorted((actual - documented) & excused_missing)
        )
        allowlisted.extend(
            f"{module_path}:orphan:{s}" for s in sorted((documented - actual) & excused_orphan)
        )
        if missing or orphans:
            drift.append(
                {
                    "module": module_path,
                    "missingInModuleMd": missing,
                    "orphanInModuleMd": orphans,
                }
            )

    details = {
        "drift": drift,
        "missingInterfaces": [d.get("missingInModuleMd", []) for d in drift],
        "touchedModules": sorted(touched),
        "allowlisted": allowlisted,
    }
    if drift:
        return False, "MODULE.md drift detected", details
    return True, "MODULE.md in sync for touched modules", details


def main() -> int:
    args = parse_args("Validate MODULE.md drift")
    issue = resolve_issue_number(args.issue)
    if issue is None:
        print("error: issue number required", file=sys.stderr)
        return 1
    passed, _, details = run_check(issue)
    detail = ""
    if details.get("changedFilesUnresolved"):
        detail = f"changed-file set unresolved: {details['changedFilesUnresolved']}"
    elif details.get("drift"):
        detail = f"{len(details['drift'])} module(s) out of sync"
    else:
        detail = (
            f"{len(details['touchedModules'])} module(s) checked, "
            f"{len(details['allowlisted'])} allowlisted symbol(s)"
        )
    return print_check_result("module_md_sync", passed, detail)


if __name__ == "__main__":
    raise SystemExit(main())
