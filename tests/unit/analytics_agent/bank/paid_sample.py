"""The paid set's stratified sample of the generated combinations (owner, 26/11): every value of
every data dimension at least once, every mode, every `create_card` kind, every advice goal,
1..5 intents, mismatches, each in a rotating seller text variant (`text_variants.json`). The
real parser, router and advisor answer; the oracle and the gap rules judge, as in the free bank.

    PYTHONPATH=backend/src:. python -m tests.unit.analytics_agent.bank.paid_sample   # rewrite
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from tests.unit.analytics_agent.bank import combos, text_variants
from tests.unit.analytics_agent.bank import dimensions as D

SAMPLE_FILE = Path(__file__).parent / "paid_sample.json"


def _strip(expect: dict[str, Any]) -> dict[str, Any]:
    """The routes come from the fakes' classify in the free bank; the paid run has none."""
    return {k: v for k, v in expect.items() if k != "routes"}


def build() -> list[dict[str, Any]]:
    t = text_variants.load_table()
    kinds = text_variants.KINDS
    out: list[dict[str, Any]] = []

    def add(case: dict[str, Any], question: str) -> None:
        out.append(
            {
                "id": f"paid.{case['id']}.{kinds[len(out) % len(kinds)]}",
                "combo_id": case["id"],
                "text_kind": kinds[len(out) % len(kinds)],
                "question": question,
                "expect": _strip(case["expect"]),
                "paid": True,
                "area": case["family"],
            }
        )

    periods = [p.id for p in D.PERIODS]
    scopes = [s.id for s in D.SCOPES]
    outputs = list(D.OUTPUTS)
    for n, m in enumerate(D.metric_ids()):  # each metric once; the other dimensions rotate
        dims = {
            "period": periods[n % len(periods)],
            "scope": scopes[n % len(scopes)],
            "metric": m,
            "output": outputs[n % len(outputs)],
        }
        case = combos.data_case(dims["period"], dims["scope"], m, dims["output"])
        add(case, text_variants.question(dims, kinds[len(out) % len(kinds)], t))
    others = {c["id"]: c for c in combos.other_families()}
    for ct in D.CARD_TYPES:  # every card kind, every slot given
        case = others[f"create.{ct}.p1d1a1"]
        q = t["card_type"][ct][kinds[len(out) % len(kinds)]]
        add(case, f"{q} cho găng tay từ 10/10 đến 12/10, giảm 10%, đơn tối thiểu 100k, 20 suất")
    for goal in D.GOALS:  # every advice goal
        case = others[f"advise.{goal}.plan.week_summary"]
        add(case, t["goal"][goal][kinds[len(out) % len(kinds)]] + " tuần tới?")
    for cid in (
        "analysis.none",
        "explain.pasted_why",
        "unsupported.gmv",
        "ambiguous.chain.none",
        "ambiguous.product.7d",
    ):
        add(others[cid], others[cid]["question"])
    for n in D.INTENT_COUNTS:  # 1..5 intents in one message
        case = others[f"intents.mixed.{n}"]
        qs = [
            text_variants.question(
                {"period": "last_week", "scope": "shop", "metric": m, "output": "value"},
                "accent",
                t,
            )
            for m in ("gmv", "orders", "aov", "ctr", "roas")[:n]
        ]
        add(case, " và ".join(q.rstrip("?") for q in qs) + "?")
    mism = [c for c in combos.mismatch_family()]
    for c in mism[:: max(1, len(mism) // 12)][:12]:  # a spread of the mismatch cases
        metric_vi = t["metric"][c["dims"]["metric"]][kinds[len(out) % len(kinds)]]
        if c["dims"]["kind"] == "card":
            what = c["dims"]["card_kind"].replace("_", " ")
            add(c, f"Thẻ {what} có làm tăng {metric_vi} không?")
        else:
            add(c, f"{metric_vi} của {' '.join(combos._SCOPE_WORDS[c['dims']['mismatch']])}?")
    return out


def write() -> None:
    body = {
        "note": "Generated by paid_sample.py; not run by default (paid). Estimate first.",
        "cases": build(),
    }
    SAMPLE_FILE.write_text(json.dumps(body, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")


def load() -> list[dict[str, Any]]:
    return list(json.loads(SAMPLE_FILE.read_text(encoding="utf-8"))["cases"])


if __name__ == "__main__":
    write()
